package io.github.nicolals.nostr.core.protocol

import io.github.nicolals.nostr.core.message.view.RelayMessageView
import io.github.nicolals.nostr.core.transport.CloseInfo
import io.github.nicolals.nostr.core.transport.TransportError
import kotlin.jvm.JvmInline

/**
 * Base interface for all inputs to the protocol engine.
 *
 * Inputs represent events that can cause state transitions:
 * - Transport lifecycle events (opened, closed, failed)
 * - Inbound relay messages
 * - User intents (subscribe, publish, close)
 * - Timer events
 *
 * NIP modules may define their own [ProtocolInput] subtypes for
 * NIP-specific intents (e.g., authentication).
 */
interface ProtocolInput

/**
 * Transport lifecycle inputs.
 *
 * These are generated by the runtime when the underlying WebSocket
 * connection state changes.
 */
sealed interface TransportInput : ProtocolInput {
    /**
     * The transport connection has been established.
     */
    data object Opened : TransportInput

    /**
     * The transport connection was closed normally.
     *
     * @property info Details about the close (code, reason, initiator).
     */
    data class Closed(val info: CloseInfo) : TransportInput

    /**
     * The transport connection failed.
     *
     * @property error The transport error that occurred.
     */
    data class Failed(val error: TransportError) : TransportInput
}

/**
 * An inbound message received from the relay.
 *
 * The [message] has already been decoded and upgraded via the message
 * upgrade registry. Reducers can pattern-match on concrete message types
 * (e.g., [io.github.nicolals.nostr.nip01.message.OkMessage]).
 *
 * @property message The upgraded relay message view.
 */
data class InboundMessage(val message: RelayMessageView) : ProtocolInput

/**
 * A timer has fired.
 *
 * Timers are scheduled via [ProtocolEffect.ScheduleTimer] and fire
 * after the specified delay. The runtime is responsible for scheduling
 * and delivering timer events.
 *
 * @property key The timer key identifying which timer fired.
 */
data class TimerFired(val key: TimerKey) : ProtocolInput

/**
 * Identifies a scheduled timer.
 *
 * Timer keys should be unique within a connection context. Common patterns:
 * - `"publish:$eventId"` for publish timeouts
 * - `"ping"` for keepalive pings
 */
@JvmInline
value class TimerKey(val value: String) {
    override fun toString(): String = value
}
